#!/usr/bin/env bash
# import_manta.sh
# Ensure Illumina Manta v1.6.0 binaries are available and on PATH.
# Can be sourced within Snakemake shell commands.

# Resolve the directory where this script resides
SCRIPT_DIR="$(cd -P "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
MANTA_BASE_DIR="$(cd "${SCRIPT_DIR}/../.." && pwd)/bin/manta"
MANTA_TARBALL="manta-1.6.0.centos6_x86_64.tar.bz2"
MANTA_URL="https://github.com/Illumina/manta/releases/download/v1.6.0/${MANTA_TARBALL}"
MANTA_DIST="manta-1.6.0.centos6_x86_64"
MANTA_INSTALL_DIR="${MANTA_BASE_DIR}/${MANTA_DIST}"
CONFIG_MANTA_BIN="${MANTA_INSTALL_DIR}/bin/configManta.py"

mkdir -p "${MANTA_BASE_DIR}"

if [ -x "$CONFIG_MANTA_BIN" ]; then
    echo "[import_manta] Using bundled Manta at ${MANTA_BASE_DIR}."
else
    exec 9>"${MANTA_BASE_DIR}/.install.lock"
    if ! flock -w 900 9; then
        echo "Error: timed out waiting for the Manta installation lock." >&2
        return 1 2>/dev/null || exit 1
    fi

    # Recheck after acquiring the lock because another job may have installed it.
    if [ ! -x "$CONFIG_MANTA_BIN" ]; then
        echo "[import_manta] Installing the official Manta binary distribution..."
        INSTALL_TMP="$(mktemp -d "${MANTA_BASE_DIR}/.install.XXXXXX")"
        TMP_TARBALL_PATH="${INSTALL_TMP}/${MANTA_TARBALL}"

        if command -v curl >/dev/null 2>&1; then
            DOWNLOAD_CMD=(curl --fail --location --retry 3 --output "$TMP_TARBALL_PATH" "$MANTA_URL")
        elif command -v wget >/dev/null 2>&1; then
            DOWNLOAD_CMD=(wget --output-document "$TMP_TARBALL_PATH" "$MANTA_URL")
        else
            echo "Error: neither curl nor wget is available to download Manta." >&2
            rm -rf "$INSTALL_TMP"
            flock -u 9
            exec 9>&-
            return 1 2>/dev/null || exit 1
        fi

        if ! "${DOWNLOAD_CMD[@]}" || ! tar -xjf "$TMP_TARBALL_PATH" -C "$INSTALL_TMP"; then
            echo "Error: failed to download or extract ${MANTA_TARBALL}." >&2
            rm -rf "$INSTALL_TMP"
            flock -u 9
            exec 9>&-
            return 1 2>/dev/null || exit 1
        fi
        if [ ! -x "${INSTALL_TMP}/${MANTA_DIST}/bin/configManta.py" ]; then
            echo "Error: downloaded Manta archive has an unexpected layout." >&2
            rm -rf "$INSTALL_TMP"
            flock -u 9
            exec 9>&-
            return 1 2>/dev/null || exit 1
        fi

        rm -rf "$MANTA_INSTALL_DIR"
        mv "${INSTALL_TMP}/${MANTA_DIST}" "$MANTA_INSTALL_DIR"
        rm -rf "$INSTALL_TMP"
        echo "[import_manta] Official Manta installation completed."
    fi
    flock -u 9
    exec 9>&-
fi

# Note: runWorkflow.py is generated by configManta.py under --runDir.
MANTA_BIN_DIR="${MANTA_INSTALL_DIR}/bin"
case ":$PATH:" in
    *":${MANTA_BIN_DIR}:"*) ;; # already in PATH
    *) export PATH="${MANTA_BIN_DIR}:$PATH" ;;
esac

if [ -f /usr/local/lib/libz.so.1 ]; then
    export LD_LIBRARY_PATH="/usr/local/lib${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}"
fi

echo "[import_manta] PATH updated to include ${MANTA_BIN_DIR}."
